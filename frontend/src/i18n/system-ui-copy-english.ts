export function humanizeEnglishKey(key: string): string {
  const words = key
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1 $2")
    .split(" ")
    .filter(Boolean)
    .map((word) => {
      const lower = word.toLowerCase();
      if (lower === "ai") return "AI";
      if (lower === "praat") return "Praat";
      if (lower === "pinyin") return "pinyin";
      if (lower === "vocab") return "vocabulary";
      return lower;
    });

  return words.length ? `${words[0][0].toUpperCase()}${words[0].slice(1)}${words.slice(1).length ? ` ${words.slice(1).join(" ")}` : ""}` : key;
}
